"""Finalize Exp 8: validate, copy into public repo, update README + NIGHTLY_LOG, pytest, commit+push.
Refuses to commit if incomplete."""
import os, json, shutil, subprocess, sys, datetime, glob
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = "/workspace/ca-adaptive-agency"
LOG = os.path.join(REPO, "NIGHTLY_LOG.md")
V = ["sw_full", "sw_pe", "sw_pecost", "sw_pecost_pe", "pecost_pe_static", "sw_pecost_pe_shuffled", "sw_no_cost"]
DEFAULT_KEY = "res100_spd0.2"; LOOSE = "res25_spd0.5"

def log(txt):
    with open(LOG, "a") as fh: fh.write(txt + "\n")
    shutil.copy(LOG, "/workspace/ca-agency-viz/NIGHTLY_LOG.md")

now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M PST")
rep_path = os.path.join(HERE, "out8", "report8.json")
if not os.path.exists(rep_path):
    log(f"\n- {now}: Exp 8 finished computing but report8.json is missing, so nothing was committed.")
    sys.exit(1)
rep = json.load(open(rep_path))
probs = []
n_pkl = len(glob.glob(os.path.join(HERE, "runs8", "cf_*.pkl")))
if n_pkl < 21: probs.append(f"only {n_pkl}/21 cf_*.pkl checkpoints")
for v in V:
    if v not in rep.get("sweep", {}):
        probs.append(f"{v} missing from sweep"); continue
    if DEFAULT_KEY not in rep["sweep"][v]:
        probs.append(f"{v} missing default threshold"); continue
    n = rep["sweep"][v][DEFAULT_KEY]["self_built"][3]
    if n < 3: probs.append(f"{v} has fewer than 3 seeds ({n})")
    for key in (DEFAULT_KEY, LOOSE):
        for m in ("self_built", "dark_any"):
            val = rep["sweep"][v][key][m][0]
            if not (val == val) or val < -1e-9 or val > 1.0 + 1e-9:
                probs.append(f"{v}.{key}.{m} out of [0,1]: {val}")
    if "default" not in rep.get("cf", {}) or v not in rep["cf"]["default"]:
        probs.append(f"{v} missing CF default scores")
if probs:
    log(f"\n- {now}: Exp 8 finished computing but did NOT pass validation, so nothing was committed: {'; '.join(probs)}.")
    sys.exit(1)

fmt = lambda c: f"{c[0]:+.4f} [{c[1]:+.4f}, {c[2]:+.4f}]" if (len(c) > 2 and c[1] == c[1]) else f"{c[0]:+.4f}"
S = rep["sweep"]; CF = rep["cf"]["default"]; verd = rep["verdict"]
m = "sw_pecost_pe"
thr_stmt = verd["threshold_fragile_pecost"]["statement"]
cf_stmt = verd["cf_own_reclass"]["statement"]

# summarize key numbers for log / README
loose_sb = {v: fmt(S[v][LOOSE]["self_built"]) for v in V if v in S}
def_sb = {v: fmt(S[v][DEFAULT_KEY]["self_built"]) for v in V if v in S}
cf_lines = []
for v in V:
    if v not in CF: continue
    cf_lines.append(f"{v}: Δleave {fmt(CF[v]['d_leave'])}, reclass_other {fmt(CF[v]['frac_reclass_other'])} (n_other≈{CF[v]['n_was_other'][0]:.0f})")

rows = "\n".join(
    f"  | {v} | {fmt(S[v][DEFAULT_KEY]['self_built'])} | {fmt(S[v][LOOSE]['self_built'])} | {fmt(S[v][DEFAULT_KEY]['dark_any'])} | {fmt(S[v][LOOSE]['dark_any'])} | {fmt(CF[v]['d_leave']) if v in CF else 'n/a'} | {fmt(CF[v]['frac_reclass_other']) if v in CF else 'n/a'} |"
    for v in V if v in S)

sec = f"""
## Experiment 8: threshold sweep + dynamic CF_own (Exp 7 follow-up)

ARCHITECTURE.md §15 #3 and NIGHTLY_LOG 2026-11-05: after Exp 7's self-built = 0 under pe_cost+depletion, do a residence/speed threshold sweep and a true counterfactual re-simulation. Reuses Exp 5 forks (step 2500), 7 variants × 3 seeds.

- **(A) Threshold sweep:** res_min ∈ {{25,50,100,200}} × spd_frac ∈ {{0.1,0.2,0.4,0.5}} (default v2 = 100 / 0.2). Regime logic is parameterized `metrics2.regimes`.
- **(B) Dynamic CF:** for ≤40 dark / high-residence targets per run, replay T=100 closed-loop steps: **ref** (unchanged), **cf_own** (subtract scalar `own` from Wl at the agent's cell, clamp ≥0), **cf_cell** (zero the cell). Score leave of resident+quiet. **Honesty:** forks store scalar `own` (decayed local deposit EMA), not a lifetime deposit map — this is a dynamic CF with the own proxy, not a recovered lifetime field.
- Dark-rooming is a separate RQ. **No agency claim is made here.**

**(i) Threshold fragility:** {thr_stmt}

**(ii) CF_own reclass:** {cf_stmt}

  | variant | self-built @100/0.2 | self-built @25/0.5 | dark_any @100/0.2 | dark_any @25/0.5 | CF Δleave (own−ref) | frac reclass among other |
  |---|---|---|---|---|---|---|
{rows}

Main arm `{m}`: self-built default {fmt(S[m][DEFAULT_KEY]['self_built'])}, loose {fmt(S[m][LOOSE]['self_built'])}; CF Δleave {fmt(CF[m]['d_leave'])}, reclass_other {fmt(CF[m]['frac_reclass_other'])}. sw_no_cost CF Δleave {fmt(CF['sw_no_cost']['d_leave'])}, reclass_other {fmt(CF['sw_no_cost']['frac_reclass_other'])}. Full tables: `figures/exp8/tables8.md`. Figures: [figures/exp8](figures/exp8). Generated by `mvp/finalize8.py` from `report8.json`.
"""

rd = open(os.path.join(REPO, "README.md")).read()
if "## Experiment 8" not in rd:
    # answer row: blunt summary
    invent = verd["threshold_fragile_pecost"].get("qualitatively_fragile",
                verd["threshold_fragile_pecost"]["any_invents_under_extreme_loose"])
    ans_i = ("Yes, qualitatively fragile at extreme thresholds" if invent
             else "No — self-built null robust (tiny/zero even at loosest grid point)")
    # CF: look at sw_no_cost reclass
    noc = CF.get("sw_no_cost", {})
    re_noc = noc.get("frac_reclass_other", [0])[0] if noc else 0
    ans_ii = f"CF_own reclass other→self (sw_no_cost frac≈{re_noc:.3f}); see section"
    ans = f"**{ans_i}.** {ans_ii}"
    rowline = f"| Exp 8 (`exp8_counterfactual.py`) | Threshold sweep + dynamic CF_own: is Exp7 self-built null fragile? Does CF reclass other-built? | {ans} |"
    anchors = [l for l in rd.split("\n") if l.startswith("| Exp 7 (`exp7_darkroom.py`)")]
    if anchors:
        rd = rd.replace(anchors[0], anchors[0] + "\n" + rowline)
    else:
        # fallback: insert before Reproduce
        pass
    rd = rd.replace("\n## Reproduce", sec + "\n## Reproduce")
    l7 = "../.venv/bin/python exp7_darkroom.py --procs 6 && ../.venv/bin/python analyze7.py   # needs the Exp 5 forks in runs5/"
    if l7 in rd:
        rd = rd.replace(l7, l7 + "\n../.venv/bin/python exp8_counterfactual.py --procs 4 && ../.venv/bin/python analyze8.py   # needs the Exp 5 forks in runs5/")
    open(os.path.join(REPO, "README.md"), "w").write(rd)

for fn in ("exp8_counterfactual.py", "analyze8.py", "run8_chain.sh", "finalize8.py", "finalize8.sh", "metrics2.py"):
    src = os.path.join(HERE, fn)
    if os.path.exists(src):
        shutil.copy(src, os.path.join(REPO, "mvp", fn))
os.makedirs(os.path.join(REPO, "figures", "exp8"), exist_ok=True)
for fn in glob.glob(os.path.join(HERE, "out8", "*")):
    shutil.copy(fn, os.path.join(REPO, "figures", "exp8"))

# ensure pytest available
py = os.path.join(HERE, "..", ".venv", "bin", "python")
subprocess.run([py, "-m", "pip", "install", "-q", "pytest"], capture_output=True)
t = subprocess.run([py, "-m", "pytest", "-q", "tests"], cwd=REPO, capture_output=True, text=True)
if t.returncode != 0:
    log(f"\n- {now}: Exp 8 results are in, but the smoke test failed, so nothing was committed. Results are in /workspace/ca-agency-viz/mvp/out8.\n  pytest: {(t.stdout + t.stderr)[:400]}")
    sys.exit(1)

summ = (f"Exp 8 (threshold sweep + dynamic CF_own) finished. (i) {thr_stmt} "
        f"(ii) Main arm {m}: CF Δleave {fmt(CF[m]['d_leave'])}, reclass_other {fmt(CF[m]['frac_reclass_other'])}; "
        f"sw_no_cost: CF Δleave {fmt(CF['sw_no_cost']['d_leave'])}, reclass_other {fmt(CF['sw_no_cost']['frac_reclass_other'])}. "
        f"self-built @100/0.2={def_sb.get(m)} vs @25/0.5={loose_sb.get(m)}. "
        f"{verd['honesty']}")
next_note = (" Next step, and why: if the self-built null is robust across thresholds and CF_own does not "
             "reclassify other-built into behavioural self-built under pe_cost+depletion, the Friston-style "
             "niche-construction path is closed under starvation in this world; a useful follow-up is either "
             "(a) a deposit-attribution instrument that logs lifetime wall maps during the main run (so CF can "
             "delete true lifetime deposits), or (b) drop pe_cost as a niche-construction lever and test a "
             "different incentive (e.g. wall-protected intake) — rather than more seeds on the same null.")
log(f"\n- {now}: {summ} Committed to the public repo (README section, figures/exp8).\n  -{next_note}")
g = lambda *a: subprocess.run(["git", "-c", "user.name=EV Campbell", "-c", "user.email=63378631+enactedvolition@users.noreply.github.com", *a], cwd=REPO, capture_output=True, text=True)
g("add", "README.md", "NIGHTLY_LOG.md", "mvp", "figures/exp8")
c = g("commit", "-m", "Exp 8: threshold sweep + dynamic CF_own on Exp 5 forks (Exp 7 follow-up)")
p = g("push", "origin", "main")
