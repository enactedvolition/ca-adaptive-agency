def d7_fires(rs):
    up = [r for r in rs if r.get("D7_sig_ratio") and (r["D7_sig_ratio"] >= 1.2 or r["D7_corr_ratio"] >= 1.2)]
    dn = [r for r in rs if r.get("D7_sig_ratio") and (r["D7_sig_ratio"] <= 1 / 1.2 or r["D7_corr_ratio"] <= 1 / 1.2)]
    return len(up) >= 3 or len(dn) >= 3
