def ci(x):
    x = np.asarray([v for v in x if v is not None and np.isfinite(v)], float)
    if len(x) == 0: return (np.nan, np.nan, np.nan, 0)
    if len(x) == 1: return (x[0], np.nan, np.nan, 1)
    m = x.mean(); h = stats.t.ppf(.975, len(x) - 1) * x.std(ddof=1) / np.sqrt(len(x)); return (m, m - h, m + h, len(x))
fmt = lambda c: f"{c[0]:+.3g} [{c[1]:+.3g}, {c[2]:+.3g}] (n={c[3]})" if c[3] > 1 else (f"{c[0]:.3g} (n=1)" if c[3] else "n/a")

